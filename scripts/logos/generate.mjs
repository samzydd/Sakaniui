/**
 * Generates src/components/ChainOfThought/logoData.ts: the brand logos <SourceLogo> draws, as one 24-unit
 * path each plus the brand colour. Paths come from Simple Icons (simpleicons.org, CC0); LinkedIn, which Simple
 * Icons no longer carries, comes from the Tabler filled set already in the library, in LinkedIn's blue.
 * A brand whose colour is (near) black is drawn in currentColor, so it stays visible on a dark surface.
 *
 *   node scripts/logos/generate.mjs
 *
 * Re-run after upgrading simple-icons. Logos are trademarks of their owners; they appear here only to name the
 * site a result came from.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const pkg = path.join(root, 'node_modules/simple-icons');
const version = JSON.parse(fs.readFileSync(path.join(pkg, 'package.json'), 'utf8')).version;
const data = JSON.parse(fs.readFileSync(path.join(pkg, 'data/simple-icons.json'), 'utf8'));
const slugOf = (i) => i.slug || i.title.toLowerCase().replace(/\+/g, 'plus').replace(/[^a-z0-9]/g, '');
const bySlug = Object.fromEntries(data.map((i) => [slugOf(i), i]));

// [name, label, simple-icons slug, colour override]
const LOGOS = [
  ['google', 'Google', 'google'],
  ['x', 'X', 'x'],
  ['reddit', 'Reddit', 'reddit'],
  ['github', 'GitHub', 'github'],
  ['linkedin', 'LinkedIn', null, '#0A66C2'],
  ['youtube', 'YouTube', 'youtube'],
  ['hackernews', 'Hacker News', 'ycombinator', '#FF6600'],
  ['wikipedia', 'Wikipedia', 'wikipedia'],
  ['stackoverflow', 'Stack Overflow', 'stackoverflow'],
  ['producthunt', 'Product Hunt', 'producthunt'],
  ['medium', 'Medium', 'medium'],
  ['notion', 'Notion', 'notion'],
  ['substack', 'Substack', 'substack'],
  ['arxiv', 'arXiv', 'arxiv'],
  ['bluesky', 'Bluesky', 'bluesky'],
  ['perplexity', 'Perplexity', 'perplexity'],
  ['duckduckgo', 'DuckDuckGo', 'duckduckgo'],
];

const isNearBlack = (hex) => {
  const n = parseInt(hex.replace('#', ''), 16);
  return ((n >> 16) & 255) + ((n >> 8) & 255) + (n & 255) < 120;
};
const pathOf = (file) => [...fs.readFileSync(file, 'utf8').matchAll(/\bd="([^"]+)"/g)].map((m) => m[1]).join(' ');

const rows = LOGOS.map(([name, label, slug, override]) => {
  let d, hex;
  if (slug) {
    const meta = bySlug[slug];
    if (!meta) throw new Error(`simple-icons has no "${slug}"`);
    d = pathOf(path.join(pkg, 'icons', `${slug}.svg`));
    hex = '#' + meta.hex;
  } else {
    const src = fs.readFileSync(path.join(root, `src/icons/filled/brand-${name}.ts`), 'utf8');
    d = [...src.matchAll(/"((?:M|m)[^"]+)"/g)].map((m) => m[1]).join(' ');
    hex = override;
  }
  if (override) hex = override;
  return { name, label, color: isNearBlack(hex) ? null : hex.toUpperCase(), path: d };
});

const header = `// Generated by scripts/logos/generate.mjs -- do not edit by hand.\n// Logo paths: Simple Icons ${version} (CC0) and the Tabler filled set (MIT). Brands are trademarks of their owners.\n`;
const body = `export interface SourceLogoData { label: string; /** brand colour; null = currentColor (a black brand) */ color: string | null; path: string }\n\nexport const SOURCE_LOGO_DATA = {\n${rows.map((r) => `  ${JSON.stringify(r.name)}: { label: ${JSON.stringify(r.label)}, color: ${JSON.stringify(r.color)}, path: ${JSON.stringify(r.path)} },`).join('\n')}\n} as const satisfies Record<string, SourceLogoData>;\n\nexport type SourceLogoName = keyof typeof SOURCE_LOGO_DATA;\n`;
fs.writeFileSync(path.join(root, 'src/components/ChainOfThought/logoData.ts'), header + body);
console.log(`${rows.length} logos`, rows.map((r) => `${r.name}${r.color ? '' : '*'}`).join(' '));
