#!/usr/bin/env node
/**
 * Builds src/regions/us.ts: the 50 states + DC as simplified SVG paths in the Albers USA
 * projection (Alaska and Hawaii inset), 975 x 610. Run by hand when the shapes need regenerating; the output is
 * committed, so nobody needs these tools to use the library.
 *
 *   mkdir /tmp/geo && cd /tmp/geo && npm i us-atlas topojson-client topojson-simplify
 *   node scripts/regions/us-states.mjs /tmp/geo/node_modules
 *
 * Source: us-atlas (U.S. Census Bureau cartographic boundaries, public domain), already projected.
 */
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const nm = resolve(process.argv[2] || 'node_modules');
const require = createRequire(nm + '/');
const { feature } = require('topojson-client');
const { presimplify, simplify, quantile } = require('topojson-simplify');
const topo = JSON.parse(readFileSync(nm + '/us-atlas/states-albers-10m.json', 'utf8'));

const NAMES = {
  '01': ['Alabama', 'AL'], '02': ['Alaska', 'AK'], '04': ['Arizona', 'AZ'], '05': ['Arkansas', 'AR'], '06': ['California', 'CA'],
  '08': ['Colorado', 'CO'], '09': ['Connecticut', 'CT'], '10': ['Delaware', 'DE'], '11': ['District of Columbia', 'DC'],
  '12': ['Florida', 'FL'], '13': ['Georgia', 'GA'], '15': ['Hawaii', 'HI'], '16': ['Idaho', 'ID'], '17': ['Illinois', 'IL'],
  '18': ['Indiana', 'IN'], '19': ['Iowa', 'IA'], '20': ['Kansas', 'KS'], '21': ['Kentucky', 'KY'], '22': ['Louisiana', 'LA'],
  '23': ['Maine', 'ME'], '24': ['Maryland', 'MD'], '25': ['Massachusetts', 'MA'], '26': ['Michigan', 'MI'], '27': ['Minnesota', 'MN'],
  '28': ['Mississippi', 'MS'], '29': ['Missouri', 'MO'], '30': ['Montana', 'MT'], '31': ['Nebraska', 'NE'], '32': ['Nevada', 'NV'],
  '33': ['New Hampshire', 'NH'], '34': ['New Jersey', 'NJ'], '35': ['New Mexico', 'NM'], '36': ['New York', 'NY'],
  '37': ['North Carolina', 'NC'], '38': ['North Dakota', 'ND'], '39': ['Ohio', 'OH'], '40': ['Oklahoma', 'OK'], '41': ['Oregon', 'OR'],
  '42': ['Pennsylvania', 'PA'], '44': ['Rhode Island', 'RI'], '45': ['South Carolina', 'SC'], '46': ['South Dakota', 'SD'],
  '47': ['Tennessee', 'TN'], '48': ['Texas', 'TX'], '49': ['Utah', 'UT'], '50': ['Vermont', 'VT'], '51': ['Virginia', 'VA'],
  '53': ['Washington', 'WA'], '54': ['West Virginia', 'WV'], '55': ['Wisconsin', 'WI'], '56': ['Wyoming', 'WY'],
};

const slim = simplify(presimplify(topo), quantile(presimplify(topo), 0.35));
const fc = feature(slim, slim.objects.states);
const r = (n) => Math.round(n * 10) / 10;

const rings = (g) => (g.type === 'Polygon' ? [g.coordinates] : g.coordinates).flat();
const out = [];
for (const f of fc.features) {
  const meta = NAMES[f.id];
  if (!meta) continue;
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity, d = '';
  let area = 0;
  for (const ring of rings(f.geometry)) {
    // tiny islands are noise at this scale
    let rx0 = Infinity, ry0 = Infinity, rx1 = -Infinity, ry1 = -Infinity;
    for (const [x, y] of ring) { rx0 = Math.min(rx0, x); ry0 = Math.min(ry0, y); rx1 = Math.max(rx1, x); ry1 = Math.max(ry1, y); }
    if ((rx1 - rx0) * (ry1 - ry0) < 1.2) continue;
    x0 = Math.min(x0, rx0); y0 = Math.min(y0, ry0); x1 = Math.max(x1, rx1); y1 = Math.max(y1, ry1);
    area += (rx1 - rx0) * (ry1 - ry0);
    d += 'M' + ring.map(([x, y]) => r(x) + ' ' + r(y)).join('L') + 'Z';
  }
  out.push({ id: meta[1], name: meta[0], d, box: [r(x0), r(y0), r(x1 - x0), r(y1 - y0)] });
}
out.sort((a, b) => a.name.localeCompare(b.name));

const here = dirname(fileURLToPath(import.meta.url));
const file = resolve(here, '../../src/regions/us.ts');
writeFileSync(file, `/* Generated by scripts/regions/us-states.mjs from us-atlas (U.S. Census Bureau, public domain). Do not edit by hand. */
import type { RegionShape } from '../components/RegionMap/types';

/** The 50 states and DC, Albers USA projection (Alaska and Hawaii inset), in a 975 x 610 box. */
export const US_STATES_VIEWBOX: [number, number, number, number] = [0, 0, 975, 610];

export const US_STATES: RegionShape[] = ${JSON.stringify(out, null, 0).replace(/},\{/g, '},\n{')};
`);
console.log(out.length, 'regions,', (readFileSync(file).length / 1024).toFixed(1), 'KB');
