/**
 * Generates src/emoji/: the Sakani emoji set, built from Fluent Emoji Flat
 * (Microsoft, MIT, via @iconify-json/fluent-emoji-flat), one module per emoji.
 *
 *   node scripts/emoji/generate.mjs
 *
 * One component per emoji (`EmojiRocket`); the five skin tones of a person or
 * hand emoji live in the same module and are picked with the `tone` prop, so
 * 3,181 pieces of artwork become 1,595 exports. Re-run after upgrading the
 * data package.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const pkgDir = path.join(root, 'node_modules/@iconify-json/fluent-emoji-flat');
const version = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8')).version;
const data = JSON.parse(fs.readFileSync(path.join(pkgDir, 'icons.json'), 'utf8'));
const chars = JSON.parse(fs.readFileSync(path.join(pkgDir, 'chars.json'), 'utf8'));
const categoriesByGroup = JSON.parse(fs.readFileSync(path.join(pkgDir, 'metadata.json'), 'utf8')).categories;

const TONES = ['medium-light', 'medium-dark', 'light', 'medium', 'dark'];
const TONE_CODEPOINT = { light: '1f3fb', 'medium-light': '1f3fc', medium: '1f3fd', 'medium-dark': '1f3fe', dark: '1f3ff' };
const outDir = path.join(root, 'src/emoji');
const artDir = path.join(outDir, 'art'); // generated modules; createEmoji.tsx beside it is hand-written
const pascal = (n) => n.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const header = `// Generated by scripts/emoji/generate.mjs -- do not edit by hand.\n// Artwork: Fluent Emoji Flat, Microsoft (MIT), data package @iconify-json/fluent-emoji-flat ${version}.\n`;

/* every drawable name -> { body, h }. Mirrored aliases (pointing right) become the parent's body, flipped. */
const art = new Map();
for (const [name, v] of Object.entries(data.icons)) if (!v.hidden) art.set(name, { body: v.body, h: v.height || 32 });
for (const [name, a] of Object.entries(data.aliases)) {
  if (!a.hFlip) continue; // plain aliases (typos, synonyms) duplicate their parent
  const parent = art.get(a.parent);
  if (parent) art.set(name, { body: `<g transform="matrix(-1 0 0 1 32 0)">${parent.body}</g>`, h: parent.h });
}

/* split `<base>-<tone>` into base + tone, only when the base exists */
const split = (n) => {
  for (const t of TONES) if (n.endsWith('-' + t) && art.has(n.slice(0, -t.length - 1))) return [n.slice(0, -t.length - 1), t];
  return [n, null];
};
const bases = new Map(); // base -> { tones: {tone: art} }
for (const n of [...art.keys()].sort()) {
  const [b, t] = split(n);
  if (!bases.has(b)) bases.set(b, { tones: {} });
  if (t) bases.get(b).tones[t] = art.get(n);
}

const charOf = new Map(Object.entries(chars).map(([cp, n]) => [n, cp]));
const toChar = (cp) => String.fromCodePoint(...cp.split('-').map((h) => parseInt(h, 16)));
const groupOf = new Map();
for (const [g, list] of Object.entries(categoriesByGroup)) for (const n of list) groupOf.set(n, g);
const labelOf = (slug) => { const s = slug.replace(/-/g, ' '); return s[0].toUpperCase() + s.slice(1); };

fs.rmSync(artDir, { recursive: true, force: true });
fs.mkdirSync(artDir, { recursive: true });

const entries = [];
const seen = new Set();
for (const [slug, { tones }] of [...bases].sort(([a], [b]) => (a < b ? -1 : 1))) {
  const main = art.get(slug);
  // the right-pointing hand is the left one mirrored: same code point with the left hand swapped for the right
  let cp = charOf.get(slug);
  if (!cp && slug.startsWith('backhand-index-pointing-right')) cp = charOf.get(slug.replace('right', 'left'))?.replace('1f448', '1f449');
  if (!cp) throw new Error('no character for ' + slug);
  const comp = 'Emoji' + pascal(slug);
  if (seen.has(comp)) throw new Error('duplicate component name ' + comp);
  seen.add(comp);

  const toneBodies = Object.fromEntries(TONES.slice().sort().filter((t) => tones[t]).map((t) => [t, tones[t].body]));
  const hasTones = Object.keys(toneBodies).length > 0;
  const bodies = [main.body, ...Object.values(toneBodies)];
  const ids = bodies.some((b) => /\bid="/.test(b));
  const opts = {};
  if (main.h !== 32) opts.h = main.h;
  if (ids) opts.ids = true;
  fs.writeFileSync(
    path.join(artDir, `${slug}.ts`),
    `${header}import { createEmoji } from '../createEmoji';\n\n` +
      `export const ${comp} = /*#__PURE__*/ createEmoji(${JSON.stringify(slug)}, ${JSON.stringify(main.body)}` +
      `${hasTones || Object.keys(opts).length ? `, ${hasTones ? JSON.stringify(toneBodies) : 'undefined'}` : ''}` +
      `${Object.keys(opts).length ? `, ${JSON.stringify(opts)}` : ''});\n` +
      `export default ${comp};\n`,
  );
  const base = slug.replace(/-(light|dark|medium)$/, '');
  entries.push({
    comp,
    slug,
    label: labelOf(slug),
    char: toChar(cp),
    category: groupOf.get(slug) || groupOf.get(base) || groupOf.get(slug.replace('right', 'left')) || 'Other',
    tones: hasTones,
  });
}

const categories = [...new Set(entries.map((e) => e.category))].sort((a, b) => Object.keys(categoriesByGroup).indexOf(a) - Object.keys(categoriesByGroup).indexOf(b));
fs.writeFileSync(
  path.join(outDir, 'catalog.ts'),
  header +
    `export type EmojiCategory = ${categories.map((c) => JSON.stringify(c)).join(' | ')};\n\n` +
    `export interface EmojiInfo {\n  /** Component name without the Emoji prefix, in kebab-case: 'waving-hand' is EmojiWavingHand. */\n  name: string;\n  /** Human name: "Waving hand". */\n  label: string;\n  /** The Unicode character, for copying or for text fallbacks. */\n  char: string;\n  category: EmojiCategory;\n  /** True when the component accepts the \`tone\` prop. */\n  tones: boolean;\n}\n\n` +
    `export const emojiCategories: readonly EmojiCategory[] = ${JSON.stringify(categories)};\n\n` +
    `/** Every emoji with its name, label, character and category: for pickers, search and galleries. */\n` +
    `export const emojiCatalog: readonly EmojiInfo[] = [\n` +
    entries.map((e) => `  ${JSON.stringify({ name: e.slug, label: e.label, char: e.char, category: e.category, tones: e.tones })},`).join('\n') +
    `\n];\n\nexport const emojiNames: readonly string[] = /*#__PURE__*/ emojiCatalog.map((e) => e.name);\n`,
);

fs.writeFileSync(
  path.join(outDir, 'index.ts'),
  header +
    `export { createEmoji } from './createEmoji';\n` +
    `export type { EmojiProps, EmojiTone, SakaniEmoji } from './createEmoji';\n` +
    `export { emojiCatalog, emojiCategories, emojiNames } from './catalog';\n` +
    `export type { EmojiCategory, EmojiInfo } from './catalog';\n\n` +
    entries.map((e) => `export { ${e.comp} } from './art/${e.slug}';`).join('\n') + '\n',
);
const withTones = entries.filter((e) => e.tones).length;
console.log(`emoji: ${entries.length} components (${withTones} with skin tones), ${art.size} pieces of artwork (${pkgDir.split('/').pop()} ${version})`);
